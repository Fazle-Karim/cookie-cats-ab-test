"""Full analysis on the raw data. Prints a report and writes docs/results.md."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd
from scipy import stats as sps

from abtest import stats as ab

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw" / "cookie_cats.csv"
OUT = ROOT / "docs" / "results.md"

ALPHA = 0.05
CONTROL, TREATMENT = "gate_30", "gate_40"
THRESHOLD = 0.005   # 0.5 percentage points: set BEFORE looking at results (see plan)


def pct(x):
    return f"{100 * x:.2f}%"


def pp(x):
    return f"{100 * x:+.2f} pp"


def main():
    df = pd.read_csv(RAW)
    df["retention_1"] = df["retention_1"].astype(int)
    df["retention_7"] = df["retention_7"].astype(int)
    c = df[df["version"] == CONTROL]
    t = df[df["version"] == TREATMENT]
    n_c, n_t = len(c), len(t)

    lines = []

    def say(text=""):
        print(text)
        lines.append(text)

    say("# Results (generated by scripts/run_analysis.py)\n")

    # 1. Is the experiment healthy? -------------------------------------------
    say("## 1. Data checks")
    chi2, p_srm = ab.sample_ratio_mismatch(n_c, n_t)
    say(f"- Players: {CONTROL} = {n_c:,}, {TREATMENT} = {n_t:,}")
    say(f"- Sample ratio check (50/50 planned): chi2 = {chi2:.2f}, p = {p_srm:.4f}")
    top = df["sum_gamerounds"].nlargest(3).tolist()
    say(f"- Largest game-round counts: {top}")
    say(f"- Players with 0 rounds: {(df['sum_gamerounds'] == 0).sum():,}")

    # 2. Primary metric: day-7 retention ---------------------------------------
    say("\n## 2. Primary metric: day-7 retention")
    x_c, x_t = int(c["retention_7"].sum()), int(t["retention_7"].sum())
    r7 = ab.two_proportion_test(x_c, n_c, x_t, n_t, ALPHA)
    boot = ab.bootstrap_diff(x_c, n_c, x_t, n_t, alpha=ALPHA)
    say(f"- {CONTROL}: {pct(r7.p_control)}   {TREATMENT}: {pct(r7.p_treatment)}")
    say(f"- Difference ({TREATMENT} - {CONTROL}): {pp(r7.diff)} "
        f"(95% CI {pp(r7.ci_low)} to {pp(r7.ci_high)})")
    say(f"- Relative change: {100 * r7.rel_lift:+.1f}%   z = {r7.z:.2f}   "
        f"p = {r7.p_value:.4f}")
    say(f"- Bootstrap 95% CI: {pp(boot['ci_low'])} to {pp(boot['ci_high'])}")
    decision = ab.classify_result(r7.ci_low, r7.ci_high, THRESHOLD)
    say(f"- Decision rule (threshold {pp(THRESHOLD)}): **{decision}**. "
        f"{ab.DECISION_TEXT[decision]}")

    # 3. Secondary metrics (corrected for running several tests) ---------------
    say("\n## 3. Secondary metrics")
    r1 = ab.two_proportion_test(int(c["retention_1"].sum()), n_c,
                                int(t["retention_1"].sum()), n_t, ALPHA)
    say(f"- Day-1 retention: {pct(r1.p_control)} vs {pct(r1.p_treatment)}, "
        f"diff {pp(r1.diff)} (95% CI {pp(r1.ci_low)} to {pp(r1.ci_high)}), "
        f"p = {r1.p_value:.4f}")

    rc, rt = c["sum_gamerounds"], t["sum_gamerounds"]
    mw = sps.mannwhitneyu(rc, rt, alternative="two-sided")
    say(f"- Game rounds, Mann-Whitney U (robust to outliers): p = {mw.pvalue:.4f}; "
        f"medians {rc.median():.0f} vs {rt.median():.0f}")

    rc_trim = rc[rc <= rc.quantile(0.999)]
    rt_trim = rt[rt <= rt.quantile(0.999)]
    w = ab.welch_from_summary(rc_trim.mean(), rc_trim.std(), len(rc_trim),
                              rt_trim.mean(), rt_trim.std(), len(rt_trim), ALPHA)
    say(f"- Game rounds, Welch t-test after removing the top 0.1%: diff "
        f"{w['diff']:+.2f} rounds (95% CI {w['ci_low']:+.2f} to {w['ci_high']:+.2f}), "
        f"p = {w['p_value']:.4f}")

    adjusted = ab.holm_adjust({"day1": r1.p_value, "rounds_mw": float(mw.pvalue),
                               "rounds_welch_trim": w["p_value"]})
    say("- Holm-adjusted p-values for the three secondary tests: "
        + ", ".join(f"{k} = {v:.4f}" for k, v in adjusted.items()))

    # 4. Could this test detect an effect that matters? ------------------------
    say("\n## 4. Power")
    n_per_group = min(n_c, n_t)
    mde = ab.minimum_detectable_effect(r7.p_control, n_per_group)
    need = ab.required_n_per_group(r7.p_control, THRESHOLD)
    say(f"- With {n_per_group:,} players per group and a baseline of "
        f"{pct(r7.p_control)}, the smallest effect detectable at 80% power is "
        f"about {pp(mde)}.")
    say(f"- Detecting {pp(THRESHOLD)} needs about {need:,} players per group.")

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nSaved report to {OUT}")


if __name__ == "__main__":
    main()
